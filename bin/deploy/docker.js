/**
 * Docker deployment helpers
 * v7.1: Dockerfile generation, build, and push
 */

const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const DOCKERFILE_TEMPLATE = `FROM node:{{NODE_VERSION}}-alpine
WORKDIR /app

COPY package*.json ./
RUN npm ci --omit=dev 2>/dev/null || npm install --omit=dev

COPY . .

ENV NODE_ENV=production
EXPOSE {{PORT}}

CMD ["node", "{{ENTRY}}"]
`;

const DOCKERIGNORE = `node_modules
npm-debug.log
.git
.gitignore
.env
deployment.zip
.aws-sam
`;

const COMPOSE_TEMPLATE = `services:
  app:
    build: .
    ports:
      - "{{PORT}}:{{PORT}}"
    environment:
      - NODE_ENV=production
    restart: unless-stopped
`;

/**
 * Generate Dockerfile
 * @param {string} serviceDir
 * @param {Object} options
 * @returns {string}
 */
function generateDockerfile(serviceDir, options = {}) {
  const resolvedDir = path.resolve(serviceDir);
  const entry = options.entry || 'service.js';
  const port = options.port || 3000;
  const nodeVersion = options.nodeVersion || '18';

  if (!fs.existsSync(path.join(resolvedDir, entry))) {
    throw new Error(`Entry file not found: ${path.join(resolvedDir, entry)}`);
  }

  const dockerfile = DOCKERFILE_TEMPLATE
    .replace(/\{\{NODE_VERSION\}\}/g, nodeVersion)
    .replace(/\{\{PORT\}\}/g, String(port))
    .replace(/\{\{ENTRY\}\}/g, entry);

  const dockerfilePath = path.join(resolvedDir, 'Dockerfile');
  fs.writeFileSync(dockerfilePath, dockerfile, 'utf8');

  const dockerignorePath = path.join(resolvedDir, '.dockerignore');
  fs.writeFileSync(dockerignorePath, DOCKERIGNORE, 'utf8');

  return dockerfilePath;
}

/**
 * Generate docker-compose.yml
 * @param {string} serviceDir
 * @param {Object} options
 * @returns {string}
 */
function generateDockerCompose(serviceDir, options = {}) {
  const resolvedDir = path.resolve(serviceDir);
  const port = options.port || 3000;
  const compose = COMPOSE_TEMPLATE.replace(/\{\{PORT\}\}/g, String(port));
  const composePath = path.join(resolvedDir, 'docker-compose.yml');
  fs.writeFileSync(composePath, compose, 'utf8');
  return composePath;
}

/**
 * Generate Docker deploy files
 * @param {string} serviceDir
 * @param {Object} options
 * @returns {Object}
 */
function generateDockerConfig(serviceDir = process.cwd(), options = {}) {
  const resolvedDir = path.resolve(serviceDir);
  const dockerfilePath = generateDockerfile(resolvedDir, options);
  const composePath = generateDockerCompose(resolvedDir, options);

  const deployDocPath = path.join(resolvedDir, 'DOCKER_DEPLOY.md');
  const entry = options.entry || 'service.js';
  const port = options.port || 3000;

  const doc = `# Docker Deployment

Generated by Navis.js v7.1

## Build and run locally

\`\`\`bash
docker build -t {{IMAGE}} .
docker run -p {{PORT}}:{{PORT}} {{IMAGE}}
\`\`\`

## Docker Compose

\`\`\`bash
docker compose up --build
\`\`\`

## Push to registry

\`\`\`bash
navis deploy docker --build --push --tag your-registry/{{IMAGE}}:latest
\`\`\`

## Files

- \`Dockerfile\` — Container image definition
- \`.dockerignore\` — Excluded paths
- \`docker-compose.yml\` — Local orchestration
- \`${entry}\` — Application entry point
`;

  const imageName = options.imageName || path.basename(resolvedDir);
  fs.writeFileSync(
    deployDocPath,
    doc.replace(/\{\{IMAGE\}\}/g, imageName).replace(/\{\{PORT\}\}/g, String(port)),
    'utf8'
  );

  return {
    serviceDir: resolvedDir,
    dockerfilePath,
    composePath,
    deployDocPath,
    entry,
    port,
  };
}

/**
 * Run docker command
 * @private
 */
function runDocker(args, cwd) {
  const result = spawnSync('docker', args, { cwd, stdio: 'inherit' });
  if (result.status !== 0) {
    throw new Error(`docker ${args[0]} failed`);
  }
  return result;
}

/**
 * Check docker is available
 */
function ensureDocker() {
  const check = spawnSync('docker', ['--version'], { stdio: 'pipe' });
  if (check.status !== 0) {
    throw new Error('Docker is not installed or not in PATH');
  }
}

/**
 * Build and optionally push Docker image
 * @param {Object} options
 * @returns {Object}
 */
function deployDocker(options = {}) {
  const serviceDir = options.dir || process.cwd();
  const imageTag = options.tag || `${path.basename(path.resolve(serviceDir))}:latest`;

  const config = options.generateOnly
    ? generateDockerConfig(serviceDir, options)
    : generateDockerConfig(serviceDir, options);

  if (options.generateOnly) {
    console.log('✅ Docker config generated:');
    console.log(`   ${config.dockerfilePath}`);
    console.log(`   ${config.composePath}`);
    console.log(`   ${config.deployDocPath}`);
    return { ...config, built: false, pushed: false };
  }

  ensureDocker();

  if (options.build || options.push) {
    console.log(`Building image: ${imageTag}`);
    runDocker(['build', '-t', imageTag, '.'], config.serviceDir);
    console.log(`✅ Built: ${imageTag}`);
  }

  if (options.push) {
    console.log(`Pushing image: ${imageTag}`);
    runDocker(['push', imageTag], config.serviceDir);
    console.log(`✅ Pushed: ${imageTag}`);
  }

  return {
    ...config,
    tag: imageTag,
    built: !!options.build || !!options.push,
    pushed: !!options.push,
  };
}

module.exports = {
  generateDockerfile,
  generateDockerCompose,
  generateDockerConfig,
  deployDocker,
};

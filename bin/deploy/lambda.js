/**
 * AWS Lambda deployment helpers
 * v7.0: Generate SAM templates and package Lambda functions
 */

const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');
const os = require('os');

const SAM_TEMPLATE = `AWSTemplateFormatVersion: '2010-09-09'
Transform: AWS::Serverless-2016-10-31
Description: Navis.js Lambda service

Globals:
  Function:
    Timeout: 30
    MemorySize: 256
    Runtime: nodejs18.x

Resources:
  NavisApi:
    Type: AWS::Serverless::Function
    Properties:
      Handler: {{HANDLER}}
      CodeUri: .
      Events:
        Api:
          Type: HttpApi
          Properties:
            Path: /{proxy+}
            Method: ANY

Outputs:
  ApiUrl:
    Description: API Gateway endpoint URL
    Value: !Sub "https://\${ServerlessHttpApi}.execute-api.\${AWS::Region}.amazonaws.com"
`;

/**
 * Generate SAM template.yaml for Lambda deployment
 * @param {string} serviceDir
 * @param {Object} options
 * @returns {string}
 */
function generateSamTemplate(serviceDir, options = {}) {
  const handler = options.handler || 'lambda.handler';
  const template = SAM_TEMPLATE.replace('{{HANDLER}}', handler);
  const target = path.join(serviceDir, 'template.yaml');

  fs.writeFileSync(target, template, 'utf8');
  return target;
}

/**
 * Generate deploy configuration files
 * @param {string} serviceDir
 * @param {Object} options
 * @returns {Object}
 */
function generateDeployConfig(serviceDir = process.cwd(), options = {}) {
  const resolvedDir = path.resolve(serviceDir);
  const entry = options.entry || 'lambda.js';

  if (!fs.existsSync(path.join(resolvedDir, entry))) {
    throw new Error(`Lambda entry not found: ${path.join(resolvedDir, entry)}`);
  }

  const templatePath = generateSamTemplate(resolvedDir, {
    handler: options.handler || `${path.basename(entry, '.js')}.handler`,
  });

  const samconfig = {
    version: 0.1,
    default: {
      deploy: {
        parameters: {
          stack_name: options.stackName || path.basename(resolvedDir),
          capabilities: 'CAPABILITY_IAM',
          confirm_changeset: false,
          resolve_s3: true,
        },
      },
    },
  };

  const samconfigPath = path.join(resolvedDir, 'samconfig.toml');
  if (!fs.existsSync(samconfigPath)) {
    const toml = `[default.deploy.parameters]
stack_name = "${samconfig.default.deploy.parameters.stack_name}"
capabilities = "CAPABILITY_IAM"
confirm_changeset = false
resolve_s3 = true
`;
    fs.writeFileSync(samconfigPath, toml, 'utf8');
  }

  const readmePath = path.join(resolvedDir, 'DEPLOY.md');
  const deployDoc = `# Deploy to AWS Lambda

Generated by Navis.js v7.0

## Prerequisites

- AWS CLI configured (\`aws configure\`)
- AWS SAM CLI (\`sam --version\`) **or** use zip upload below

## Option 1: SAM Deploy

\`\`\`bash
sam build
sam deploy --guided
\`\`\`

## Option 2: Zip + AWS CLI

\`\`\`bash
navis deploy lambda --zip-only
aws lambda update-function-code --function-name YOUR_FUNCTION --zip-file fileb://deployment.zip
\`\`\`

## Files

- \`${entry}\` — Lambda handler
- \`template.yaml\` — AWS SAM template
- \`samconfig.toml\` — SAM deploy defaults
`;

  fs.writeFileSync(readmePath, deployDoc, 'utf8');

  return {
    serviceDir: resolvedDir,
    templatePath,
    samconfigPath,
    deployDocPath: readmePath,
    entry,
  };
}

/**
 * Package Lambda function into deployment.zip
 * @param {string} serviceDir
 * @param {Object} options
 * @returns {string} zip path
 */
function packageLambda(serviceDir = process.cwd(), options = {}) {
  const resolvedDir = path.resolve(serviceDir);
  const entry = options.entry || 'lambda.js';
  const zipPath = path.join(resolvedDir, options.zipName || 'deployment.zip');

  if (fs.existsSync(zipPath)) {
    fs.unlinkSync(zipPath);
  }

  const files = [entry];
  const pkgPath = path.join(resolvedDir, 'package.json');
  if (fs.existsSync(pkgPath)) {
    files.push('package.json');
  }

  if (process.platform === 'win32') {
    const tempDir = fs.mkdtempSync(path.join(os.tmpdir(), 'navis-deploy-'));
    for (const file of files) {
      fs.copyFileSync(path.join(resolvedDir, file), path.join(tempDir, file));
    }
    const result = spawnSync(
      'powershell',
      [
        '-NoProfile',
        '-Command',
        `Compress-Archive -Path '${tempDir}\\*' -DestinationPath '${zipPath}' -Force`,
      ],
      { stdio: 'pipe' }
    );
    fs.rmSync(tempDir, { recursive: true, force: true });
    if (result.status !== 0) {
      throw new Error(`Failed to create zip: ${result.stderr?.toString() || 'unknown error'}`);
    }
  } else {
    const result = spawnSync('zip', ['-j', zipPath, ...files.map((f) => path.join(resolvedDir, f))], {
      cwd: resolvedDir,
      stdio: 'pipe',
    });
    if (result.status !== 0) {
      throw new Error(
        'zip command failed. Install zip or run on Windows for automatic packaging.'
      );
    }
  }

  return zipPath;
}

/**
 * Deploy Lambda using SAM CLI if available
 * @param {Object} options
 * @returns {Object}
 */
function deployLambda(options = {}) {
  const serviceDir = options.dir || process.cwd();
  const config = generateDeployConfig(serviceDir, options);

  let zipPath = null;
  if (options.zipOnly || options.package) {
    zipPath = packageLambda(serviceDir, options);
    console.log(`✅ Packaged: ${zipPath}`);
  }

  if (options.zipOnly) {
    return { ...config, zipPath, deployed: false };
  }

  const sam = spawnSync('sam', ['--version'], { stdio: 'pipe' });
  if (sam.status !== 0) {
    if (!zipPath) {
      zipPath = packageLambda(serviceDir, options);
    }
    console.log('⚠️  AWS SAM CLI not found. Generated deployment files and zip.');
    console.log(`   Zip: ${zipPath}`);
    console.log('   See DEPLOY.md for manual upload instructions.');
    return { ...config, zipPath, deployed: false, reason: 'sam-not-found' };
  }

  console.log('Building with SAM...');
  const build = spawnSync('sam', ['build'], { cwd: config.serviceDir, stdio: 'inherit' });
  if (build.status !== 0) {
    throw new Error('sam build failed');
  }

  const deployArgs = ['deploy'];
  if (options.guided) {
    deployArgs.push('--guided');
  } else {
    deployArgs.push('--no-confirm-changeset');
  }

  console.log('Deploying with SAM...');
  const deploy = spawnSync('sam', deployArgs, { cwd: config.serviceDir, stdio: 'inherit' });
  if (deploy.status !== 0) {
    throw new Error('sam deploy failed');
  }

  return { ...config, zipPath, deployed: true };
}

module.exports = {
  generateSamTemplate,
  generateDeployConfig,
  packageLambda,
  deployLambda,
};
